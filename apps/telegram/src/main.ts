import { mountGame } from '@minimorph/game-ui';
import '@minimorph/game-ui/style.css';
import { initializeTelegram, loadTelegramBridge } from './telegram';
const game = mountGame(document.querySelector<HTMLElement>('#app')!, 'TELEGRAM / FREE PLAY');
game.setHostStatus('Browser practice · connecting to Telegram…');
let destroyed = false;
let host: ReturnType<typeof initializeTelegram> | undefined;
void loadTelegramBridge().then(() => { if (!destroyed) { host = initializeTelegram(); game.setHostStatus(host.label); } });
window.addEventListener('pagehide', () => { destroyed = true; host?.destroy(); game.destroy(); }, { once: true });
window.addEventListener('pageshow', e => { if (e.persisted) window.location.reload(); });
