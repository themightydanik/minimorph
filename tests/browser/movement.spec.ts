import { test, expect } from '@playwright/test';
import { chooseAndStart } from '../helpers/race-ui';
test('production character follows jump, forward dive, slide, recovery and run', async ({ page }, info) => {
  test.setTimeout(120000);
  await page.clock.install();
  await page.goto('http://127.0.0.1:5173');
  const canvas = page.locator('canvas');
  await expect(canvas).toHaveAttribute('data-character', 'minimorph-optimized-v1', { timeout: 60000 });
  await page.clock.pauseAt(await page.evaluate(() => Date.now() + 1000));
  await chooseAndStart(page, 'Cosmic Sprint', true);
  await canvas.focus(); await page.keyboard.down('KeyW'); await page.clock.runFor(220);
  await page.keyboard.press('Space'); await page.clock.runFor(180);
  await expect(canvas).toHaveAttribute('data-character-clip', 'Jump');
  await page.keyboard.down('ShiftLeft'); await page.clock.runFor(50);
  await expect(canvas).toHaveAttribute('data-action', 'dive');
  await expect(canvas).toHaveAttribute('data-character-clip', 'Fall');
  await page.screenshot({ path: `test-results/pr9-dive-${info.project.name}.png` });
  // Step explicitly so short action phases cannot be skipped by the assertion clock.
  for (let i = 0; i < 30 && await canvas.getAttribute('data-action') === 'dive'; i++) await page.clock.runFor(20);
  await expect(canvas).toHaveAttribute('data-action', 'slide');
  await page.clock.runFor(100);
  expect(Number(await canvas.getAttribute('data-character-pitch'))).toBeLessThan(-45);
  await page.screenshot({ path: `test-results/pr9-slide-${info.project.name}.png` });
  for (let i = 0; i < 30 && await canvas.getAttribute('data-action') === 'slide'; i++) await page.clock.runFor(20);
  await expect(canvas).toHaveAttribute('data-action', 'recover');
  await expect(canvas).toHaveAttribute('data-character-clip', 'Land');
  await page.clock.runFor(400); await expect(canvas).toHaveAttribute('data-action', 'normal');
  await expect(canvas).toHaveAttribute('data-character-clip', 'Run');
  await page.keyboard.up('ShiftLeft');
  await page.keyboard.up('KeyW');
});
test('mobile analog stick supports partial intensity, three fingers and cancellation without stuck input', async ({ page }, info) => {
  test.skip(info.project.name !== 'mobile', 'Touch-specific pointer capture');
  test.setTimeout(120000);
  await page.clock.install(); await page.goto('http://127.0.0.1:5173');
  const canvas = page.locator('canvas');
  await expect(canvas).toHaveAttribute('data-character', 'minimorph-optimized-v1', { timeout: 60000 });
  await page.clock.pauseAt(await page.evaluate(() => Date.now() + 1000));
  await chooseAndStart(page, 'Cosmic Sprint', true);
  const stick = page.getByRole('group', { name: 'Movement joystick' }), box = (await stick.boundingBox())!;
  const cdp = await page.context().newCDPSession(page);
  const finger = { x: box.x + box.width / 2, y: box.y + box.height / 2, id: 1 };
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [finger] });
  await expect(stick).toHaveAttribute('data-x', '0'); await expect(stick).toHaveAttribute('data-z', '0');
  finger.y -= box.width * .16;
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [finger] });
  await expect.poll(async () => Math.abs(Number(await stick.getAttribute('data-z')))).toBeGreaterThan(.3);
  const partial = Math.abs(Number(await stick.getAttribute('data-z')));
  expect(partial).toBeGreaterThan(.3); expect(partial).toBeLessThan(.6);
  finger.x += box.width * .18; finger.y -= box.width * .14;
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [finger] }); await page.clock.runFor(150);
  await expect.poll(async () => Number(await stick.getAttribute('data-x'))).toBeGreaterThan(.3);
  expect(Number(await stick.getAttribute('data-z'))).toBeLessThan(-.7);
  const jump = (await page.getByRole('button', { name: 'Jump', exact: true }).boundingBox())!;
  const dive = (await page.getByRole('button', { name: 'Dive', exact: true }).boundingBox())!;
  const second = { x: jump.x + jump.width / 2, y: jump.y + jump.height / 2, id: 2 };
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [finger, second] }); await page.clock.runFor(100);
  await expect(canvas).toHaveAttribute('aria-description', 'Airborne');
  const third = { x: dive.x + dive.width / 2, y: dive.y + dive.height / 2, id: 3 };
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [finger, second, third] }); await page.clock.runFor(40);
  await expect(canvas).toHaveAttribute('data-action', 'dive');
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] });
  await expect(stick).toHaveAttribute('data-x', '0'); await expect(stick).toHaveAttribute('data-z', '0');
  await expect(page.locator('.touch-controls .pressed')).toHaveCount(0);
  await page.screenshot({ path: 'test-results/pr9-analog-mobile.png' });
  await cdp.detach();
});
